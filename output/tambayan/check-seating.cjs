// First compile seating-planner.ts to .check with tsc --module commonjs.
const assert = require('node:assert/strict')
const { createSeatSlots, SeatingPlanner } = require('./.check/seating-planner.js')
const room = { x: 438, y: 245, w: 524, h: 445 }
const slots = createSeatSlots(room)
assert.equal(slots.length, 24)
assert.equal(new Set(slots.map(s => s.id)).size, 24)
const planner = new SeatingPlanner(slots)
assert.equal(planner.update(1, new Set(), 0).capacity, 6)
assert.equal(planner.update(8, new Set(), 100).capacity, 12)
assert.equal(planner.update(16, new Set(), 200).capacity, 18)
assert.equal(planner.update(22, new Set(), 300).capacity, 24)
assert.equal(planner.update(1, new Set(), 400).capacity, 24)
assert.equal(planner.update(1, new Set(), 60399).capacity, 24)
assert.equal(planner.update(1, new Set(), 60400).capacity, 6)
const occupied = new Set([slots[23].id])
const retained = planner.update(1, occupied, 61000)
assert(retained.seats.some(s => occupied.has(s.id)))
assert.equal(planner.update(30, new Set(), 62000).overflow, 6)
const first = slots[0]
assert(!createSeatSlots(room, [{ x: first.x, y: first.y, w: 30, h: 28 }]).some(s => s.id === first.id))
assert.deepEqual(createSeatSlots({ x: 0, y: 0, w: 100, h: 100 }), [])
assert.equal(new SeatingPlanner([]).update(10, new Set(), 0).overflow, 10)
console.log('Seating checks passed: capacity, stable IDs, delayed shrink, occupied retention, obstacles, overflow.')
